const skipTags = new Set(["SCRIPT", "STYLE", "TEXTAREA", "INPUT", "OPTION", "CODE", "PRE", "NOSCRIPT"]);
const originalText = new WeakMap();
const originalPlaceholder = new WeakMap();
const remoteCache = new Map(JSON.parse(localStorage.getItem("a2_translation_cache_ar") || "[]"));
const pendingNodes = new Map();
let observer;
let queueTimer;

export function currentLanguage() { return localStorage.getItem("a2_language") || "en"; }
function cleanText(text) { return String(text || "").replace(/\s+/g, " ").trim(); }
function hasLetters(text) { return /[A-Za-zأ-ي]/.test(text); }
function isArabic(text) { return /[\u0600-\u06FF]/.test(text); }
function shouldRemoteTranslate(text) { const clean = cleanText(text); if (!clean || clean.length < 2 || clean.length > 850) return false; if (!hasLetters(clean) || isArabic(clean)) return false; if (/^[\d\s:.,/#@+\-()]+$/.test(clean)) return false; return true; }
function storeCache() { try { localStorage.setItem("a2_translation_cache_ar", JSON.stringify([...remoteCache.entries()].slice(-900))); } catch {} }

function translateText(text, lang) {
  const clean = cleanText(text);
  if (!clean || lang === "en") return text;
  return dictionary[lang]?.[clean] || remoteCache.get(clean) || text;
}

async function remoteTranslate(text) {
  const clean = cleanText(text);
  if (remoteCache.has(clean)) return remoteCache.get(clean);
  const url = `https://api.mymemory.translated.net/get?q=${encodeURIComponent(clean)}&langpair=en|ar`;
  const response = await fetch(url);
  const data = await response.json();
  const translated = cleanText(data?.responseData?.translatedText || "");
  if (translated && translated !== clean) {
    remoteCache.set(clean, translated);
    storeCache();
    return translated;
  }
  return clean;
}

function enqueue(node, base) {
  if (!shouldRemoteTranslate(base)) return;
  const clean = cleanText(base);
  if (remoteCache.has(clean)) {
    node.nodeValue = base.replace(clean, remoteCache.get(clean));
    return;
  }
  pendingNodes.set(node, clean);
  clearTimeout(queueTimer);
  queueTimer = setTimeout(processQueue, 450);
}

async function processQueue() {
  const items = [...pendingNodes.entries()].slice(0, 10);
  items.forEach(([node]) => pendingNodes.delete(node));
  for (const [node, text] of items) {
    if (currentLanguage() !== "ar") return;
    try {
      const translated = await remoteTranslate(text);
      const base = originalText.get(node) || node.nodeValue;
      if (currentLanguage() === "ar" && document.body?.contains(node)) node.nodeValue = String(base).replace(text, translated);
    } catch {}
  }
  if (pendingNodes.size) queueTimer = setTimeout(processQueue, 900);
}

function walk(node, lang) {
  if (!node) return;
  if (node.nodeType === Node.TEXT_NODE) {
    const base = originalText.get(node) || node.nodeValue;
    if (!originalText.has(node)) originalText.set(node, base);
    const translated = translateText(base, lang);
    if (translated !== node.nodeValue) node.nodeValue = translated;
    if (lang === "ar" && translated === base) enqueue(node, base);
    if (lang === "en" && node.nodeValue !== base) node.nodeValue = base;
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE || skipTags.has(node.tagName)) return;
  if (node.closest?.("[data-no-translate]")) return;
  const placeholder = node.getAttribute?.("placeholder");
  if (placeholder !== null) {
    const base = originalPlaceholder.get(node) || placeholder;
    if (!originalPlaceholder.has(node)) originalPlaceholder.set(node, base);
    const translated = translateText(base, lang);
    node.setAttribute("placeholder", lang === "en" ? base : translated);
  }
  [...node.childNodes].forEach((child) => walk(child, lang));
}

export function applyLanguage(language = currentLanguage()) {
  const lang = language === "ar" ? "ar" : "en";
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.body?.setAttribute("data-language", lang);
  walk(document.body, lang);
}

export function startAutoTranslate() {
  applyLanguage(currentLanguage());
  window.addEventListener("a2-language-change", (event) => applyLanguage(event.detail?.language || currentLanguage()));
  if (observer) observer.disconnect();
  observer = new MutationObserver(() => applyLanguage(currentLanguage()));
  observer.observe(document.body, { childList: true, subtree: true, characterData: true });
}
